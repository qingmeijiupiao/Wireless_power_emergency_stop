from generate_diagnostic_pages import icon, FONT, SMALL, ROOT, centered

def pack(im):
    return [sum((1 << bit) if page*8+bit < im.height and im.getpixel((x,page*8+bit)) else 0
                for bit in range(8)) for page in range((im.height+7)//8) for x in range(im.width)]

def array(data):
    return '{'+','.join(str(n) for n in data)+'}'

