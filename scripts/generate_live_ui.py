large=ImageFont.truetype('C:/Windows/Fonts/consolab.ttf',20)
small=ImageFont.truetype('C:/Windows/Fonts/consola.ttf',10)
def glyphs(font,width,height):
    result=[]
    for code in range(32,127):
        im=Image.new('1',(width,height));d=ImageDraw.Draw(im)
        box=d.textbbox((0,0),chr(code),font=font)
        d.text((-box[0],-font.getbbox('0')[1]),chr(code),font=font,fill=1)
        result.append(array(pack(im)))
    return ',\n'.join(result)
